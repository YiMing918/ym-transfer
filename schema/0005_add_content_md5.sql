-- ym-transfer 数据库迁移 0005：文件内容指纹
-- 上传完成确认时，把 R2 对象自带的 etag（单次预签名 PUT 的对象 etag
-- 即内容 MD5，32 位十六进制）存进 content_md5，结果面板会显示出来，
-- 把链接给别人时可连指纹一起给，对方下完能核对文件没被换过。
-- 老文件该列为 NULL：没存过指纹，不显示指纹行，下载一切照旧。
-- 本迁移没跑的库：代码有兜底（complete 写指纹是尽力而为，写失败直接
-- 跳过），上传/确认/下载一切照旧，只是没有指纹可存；跑了本迁移即自动生效。
-- 改表须新增编号迁移文件，不要改旧文件（已部署的库不会重跑旧文件）。
ALTER TABLE files ADD COLUMN content_md5 TEXT;
